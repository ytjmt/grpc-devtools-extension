import react from "@vitejs/plugin-react";
import { join } from "node:path";
import { defineConfig } from "vite-plus";
import { playwright } from "vite-plus/test/browser-playwright";

// Root config for Vite+: tests, formatting, and linting. The extension and the
// example client build with their own configs (extension/, example/client/).

const browser = (viewport: { width: number; height: number }) => ({
  enabled: true,
  provider: playwright(),
  headless: true,
  instances: [{ browser: "chromium" as const }],
  viewport,
});

export default defineConfig({
  plugins: [react()],
  test: {
    projects: [
      {
        extends: true,
        test: { name: "unit", include: ["tests/unit/**/*.test.ts"], environment: "node" },
      },
      {
        extends: true,
        test: {
          name: "component",
          include: ["tests/component/**/*.test.tsx"],
          setupFiles: ["tests/support/browser-setup.ts"],
          browser: browser({ width: 1000, height: 700 }),
        },
      },
      {
        // `vp run test:vrt` sets VRT after starting the browser container; other runs skip these tests.
        extends: true,
        test: {
          name: "vrt",
          include: process.env.VRT ? ["tests/vrt/**/*.test.tsx"] : [],
          setupFiles: ["tests/support/browser-setup.ts", "tests/support/vrt-setup.ts"],
          browser: {
            ...browser({ width: 1000, height: 700 }),
            // Chromium runs in the Playwright container (compose.yaml); `<loopback>`
            // lets it reach the Vitest server on this host as localhost.
            provider: playwright({
              connectOptions: { wsEndpoint: "ws://127.0.0.1:3000/", exposeNetwork: "<loopback>" },
            }),
            expect: {
              toMatchScreenshot: {
                // Rendering is always Linux, whatever the host OS.
                resolveScreenshotPath: ({
                  root,
                  testFileDirectory,
                  screenshotDirectory,
                  testFileName,
                  arg,
                  browserName,
                  ext,
                }) =>
                  join(root, testFileDirectory, screenshotDirectory, testFileName, `${arg}-${browserName}-linux${ext}`),
                comparatorName: "pixelmatch",
                // Rendering in Docker is deterministic; any changed pixel beyond anti-aliasing noise fails.
                comparatorOptions: { threshold: 0.1, allowedMismatchedPixels: 0 },
              },
            },
          },
        },
      },
    ],
  },
  fmt: {
    // The code base was written at this width.
    printWidth: 120,
    // Generated by `vp run example:gen`.
    ignorePatterns: ["example/gen/**"],
  },
  // Run by the pre-commit hook (.vite-hooks/pre-commit) on staged files.
  staged: {
    "*": "vp check --fix",
    ".github/workflows/*.yml": "actionlint",
    // Checks the whole lockfile, so the staged paths are dropped.
    ".github/**": "sh -c 'gh-actions-lock --verify-local --no-fix' --",
  },
  lint: {
    ignorePatterns: ["example/gen/**"],
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: { "vite-plus/prefer-vite-plus-imports": "error" },
    overrides: [
      {
        files: ["extension/src/core/**"],
        rules: {
          "no-restricted-imports": [
            "error",
            {
              patterns: [
                {
                  group: ["react", "react-dom", "react/*", "react-dom/*", "../panel/*"],
                  message: "core/ stays free of UI code.",
                },
              ],
            },
          ],
          "no-restricted-globals": [
            "error",
            { name: "chrome", message: "core/ does not call chrome.* APIs; pass data in instead." },
          ],
        },
      },
      {
        // UI text goes through the i18n catalog; punctuation and .proto keywords may stay inline.
        files: ["extension/src/panel/**/*.tsx"],
        plugins: ["react"],
        rules: {
          "react/jsx-no-literals": [
            "error",
            {
              noStrings: false,
              ignoreProps: true,
              allowedStrings: ["✕", "·", "—", "→", ".", ":", "#", "(", ")", '"', "oneof"],
            },
          ],
        },
      },
    ],
    options: { typeAware: true, typeCheck: true },
  },
});
